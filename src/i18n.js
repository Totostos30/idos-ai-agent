// Два языка интерфейса (Γλῶτта §i18n): ключи словаря — исходные русские строки интерфейса.
// t(s): «ru» возвращает строку как есть, «en» берёт EN[s] или возвращает русский оригинал —
// поэтому непереведённый кусок не ломает интерфейс. t(s, params) подставляет {имена}.
// Язык хранится в настройке ядра language (config.py: "language": "ru") и в localStorage
// для мгновенного старта до ответа ядра.
let LANG = "ru";
try { LANG = localStorage.getItem("idos.lang") === "en" ? "en" : "ru"; } catch (_) { /* приватный режим */ }

// Активный язык: "ru" | "en".
export const lang = () => LANG;
// Локаль для дат/чисел: toLocaleDateString(locale(), …).
export const locale = () => (LANG === "en" ? "en-US" : "ru-RU");

// Перевод строки-ключа; params подставляет {имя} → значение.
export function t(s, params) {
  let out = LANG === "en" ? (EN[s] || s) : s;
  if (params) for (const [k, v] of Object.entries(params)) out = out.split("{" + k + "}").join(String(v));
  return out;
}

// Сменить язык: localStorage + <html lang> + настройка ядра (если ядро доступно).
export function setLang(next) {
  LANG = next === "en" ? "en" : "ru";
  try { localStorage.setItem("idos.lang", LANG); } catch (_) { /* ignore */ }
  document.documentElement.lang = LANG;
  const core = typeof window !== "undefined" && window.idos && window.idos.core;
  if (core) core.try("settings.set", { key: "language", value: LANG });
}

// Инициализация: мгновенно применить кэш, затем согласовать с настройкой ядра
// (ядро — источник истины; событие settings.changed прилетает в оба окна).
export function initI18n(core) {
  document.documentElement.lang = LANG;
  core.on("core.connected", async () => {
    const s = await core.try("settings.get", {}, 8000);
    const coreLang = s && !s.error && (s.language === "ru" || s.language === "en") ? s.language : null;
    if (coreLang && coreLang !== LANG) setLang(coreLang);
  });
  // смена языка из другого окна (настройки применяются ко всем окнам сразу)
  core.on("settings.changed", async ({ key }) => {
    if (key !== "language") return;
    const s = await core.try("settings.get", {}, 8000);
    const coreLang = s && !s.error && (s.language === "ru" || s.language === "en") ? s.language : null;
    if (coreLang && coreLang !== LANG) setLang(coreLang);
    window.dispatchEvent(new CustomEvent("idos.lang"));
  });
}

